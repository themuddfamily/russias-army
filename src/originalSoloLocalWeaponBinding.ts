import * as THREE from 'three';
import type {WeaponId} from '../shared/protocol';
import {createOriginalWeaponMotion,type OriginalWeaponMotionState} from '../shared/originalWeaponMotion';
import {validateReceiverScenePrefix,type ReceiverScenePrefix} from '../shared/originalReceiverPrefix';
import {ORIGINAL_RECEIVER_LOCAL_WEAPON_RESOURCES,type ReceiverLocalWeaponHandle,type ReceiverLocalWeaponModelCapture} from '../shared/originalReceiverLocalWeaponInventory';
import type {ReceiverLocalWeaponBindingOperation,ReceiverLocalWeaponWorldCheckpoint,ReceiverLocalWeaponWorldOptions} from '../shared/originalReceiverLocalWeaponWorld';
import type {OriginalWeaponCollection} from './originalWeapons';
import {ORIGINAL_WEAPON_ROTATION,ORIGINAL_WEAPON_UNIT_SCALE} from './originalWeaponPresentation';

const handles=Object.freeze(Object.keys(ORIGINAL_RECEIVER_LOCAL_WEAPON_RESOURCES) as ReceiverLocalWeaponHandle[]);
const weaponHandles:Readonly<Record<WeaponId,ReceiverLocalWeaponHandle>>=Object.freeze({pistol:'pistol',shotgun:'spas12',rifle:'ak47',launcher:'rg6',rpg:'rpg',sniper:'dragunov'});
const normalized=(text:string)=>text.trim().toLowerCase();
const unit=new THREE.Matrix4().makeScale(ORIGINAL_WEAPON_UNIT_SCALE,ORIGINAL_WEAPON_UNIT_SCALE,ORIGINAL_WEAPON_UNIT_SCALE);
const rotation=new THREE.Quaternion().setFromEuler(ORIGINAL_WEAPON_ROTATION);
function matrix(values:readonly number[]):THREE.Matrix4 {
 if(!Array.isArray(values)||values.length!==16)throw Error('Invalid local weapon matrix count');
 for(let i=0;i<16;i++)if(!Number.isFinite(values[i]))throw Error('Nonfinite local weapon matrix');
 if(values[3]!==0||values[7]!==0||values[11]!==0||values[15]!==1)throw Error('Nonaffine local weapon matrix');
 const result=new THREE.Matrix4().fromArray(values),determinant=result.determinant();
 if(!Number.isFinite(determinant)||determinant===0)throw Error('Singular local weapon matrix');
 if(!result.clone().invert().elements.every(Number.isFinite))throw Error('Local weapon inverse overflow');
 return result;
}
function checked(value:THREE.Matrix4):THREE.Matrix4 {
 // Only matrices generated by our affine algebra are canonicalized. Generic
 // inversion can round the homogeneous1; borrowed/captured inputs stay strict.
 const e=value.elements;
 if(!e.every(Number.isFinite)||Math.abs(e[3])>1e-10||Math.abs(e[7])>1e-10||Math.abs(e[11])>1e-10||Math.abs(e[15]-1)>1e-10)throw Error('Local weapon matrix arithmetic overflow');
 e[3]=e[7]=e[11]=0;e[15]=1;return matrix(e);
}
function inverse(value:THREE.Matrix4):THREE.Matrix4 {return checked(value.clone().invert());}
const frozenMatrix=(value:THREE.Matrix4):readonly number[]=>Object.freeze([...checked(value).elements]);
function prefixCopy(value:ReceiverScenePrefix):ReceiverScenePrefix {
 validateReceiverScenePrefix(value);
 return Object.freeze(value.kind==='receipt'?{kind:value.kind,sceneGeneration:value.sceneGeneration,callback:value.callback,tick:value.tick}:{kind:value.kind,sceneGeneration:value.sceneGeneration,callback:value.callback});
}
function limit(value:number):void {if(!Number.isSafeInteger(value)||value<=0||value>65536)throw Error('Invalid local weapon text bound');}
function copyCheckpoint(input:ReceiverLocalWeaponWorldCheckpoint,maxTextChars:number):ReceiverLocalWeaponWorldCheckpoint {
 limit(maxTextChars);
 if(!input||!Array.isArray(input.models)||input.models.length!==7||typeof input.loadedRocket!=='boolean')throw Error('Invalid local weapon checkpoint shape');
 const prefix=prefixCopy(input.prefix),cameraHandle=input.cameraHandle;
 if(typeof cameraHandle!=='string'||!normalized(cameraHandle)||handles.includes(normalized(cameraHandle) as ReceiverLocalWeaponHandle)||['smokes','gsmokes'].includes(normalized(cameraHandle)))throw Error('Invalid local weapon camera handle');
 let text=cameraHandle.length;const seen=new Set<string>(),ancestry=new Map<string,readonly string[]>();
 if(text>maxTextChars)throw Error('Local weapon text budget exceeded');
 // Count and validate all records before allocating any ancestry or matrix copies.
 for(const model of input.models as readonly ReceiverLocalWeaponModelCapture[]){
  if(!model||!handles.includes(model.handle)||seen.has(model.handle)||model.resource!==ORIGINAL_RECEIVER_LOCAL_WEAPON_RESOURCES[model.handle]||typeof model.inWorld!=='boolean'||!Array.isArray(model.groupAncestry)||model.groupAncestry.length>maxTextChars)throw Error('Invalid local weapon model');
  seen.add(model.handle);matrix(model.worldMatrix);text+=model.handle.length+model.resource.length;
  const groups=new Set<string>();
  for(const group of model.groupAncestry){
   if(typeof group!=='string'||!normalized(group)||normalized(group)===model.handle||['smokes','gsmokes'].includes(normalized(group))||groups.has(normalized(group)))throw Error('Invalid local weapon ancestry');
   groups.add(normalized(group));text+=group.length;if(text>maxTextChars)throw Error('Local weapon text budget exceeded');
  }
  ancestry.set(model.handle,[...groups]);
 }
 if(text>maxTextChars)throw Error('Local weapon text budget exceeded');
 const visiting=new Set<string>(),visited=new Set<string>();
 const visit=(handle:string)=>{if(visiting.has(handle))throw Error('Cyclic local weapon ancestry');if(visited.has(handle))return;visiting.add(handle);for(const group of ancestry.get(handle)??[])if(ancestry.has(group))visit(group);visiting.delete(handle);visited.add(handle);};
 for(const handle of handles)visit(handle);
 const motion=createOriginalWeaponMotion(input.motion);if(motion.weapon!==input.selectedWeapon)throw Error('Local weapon motion selection mismatch');
 return Object.freeze({prefix,cameraHandle,cameraWorldMatrix:frozenMatrix(matrix(input.cameraWorldMatrix)),selectedWeapon:input.selectedWeapon,loadedRocket:input.loadedRocket,motion,
  models:Object.freeze(input.models.map(model=>Object.freeze({handle:model.handle,resource:model.resource,inWorld:model.inWorld,worldMatrix:frozenMatrix(matrix(model.worldMatrix)),groupAncestry:Object.freeze([...model.groupAncestry])})))});
}

export interface OriginalSoloLocalWeaponSeedOptions {
 readonly prefix:ReceiverScenePrefix;readonly cameraHandle:string;readonly cameraWorldMatrix:readonly number[];
 readonly renderToWorld:readonly number[];readonly selectedWeapon:WeaponId|null;readonly loadedRocket:boolean;
 readonly motion:OriginalWeaponMotionState;readonly membership:Readonly<Record<ReceiverLocalWeaponHandle,boolean>>;
 readonly ancestry:Readonly<Record<ReceiverLocalWeaponHandle,readonly string[]>>;readonly maxTextChars:number;
}
/** Capture already-updated borrowed resource WORLD matrices without touching a
 * renderer. Geometry was scaled on import, so raw geometry receives that unit
 * scale exactly once here. Membership and ancestry are explicit caller facts;
 * visibility, parent pointers and logical selection cannot establish them. */
export function captureOriginalSoloLocalWeaponSeed(collection:OriginalWeaponCollection,options:OriginalSoloLocalWeaponSeedOptions):ReceiverLocalWeaponWorldCheckpoint {
 if(!options||!collection||!(collection.resources instanceof Map)||!options.membership||!options.ancestry)throw Error('Invalid local weapon seed');
 limit(options.maxTextChars);const transform=matrix(options.renderToWorld),seen=new Set<THREE.Mesh>();
 const models:ReceiverLocalWeaponModelCapture[]=[];
 for(const handle of handles){
  const resource=ORIGINAL_RECEIVER_LOCAL_WEAPON_RESOURCES[handle],mesh=collection.resources.get(resource);
  if(!(mesh instanceof THREE.Mesh)||seen.has(mesh)||handle==='rocket'&&mesh!==collection.rocket)throw Error('Missing or aliased local weapon resource');
  seen.add(mesh);
  const ancestry=options.ancestry[handle],inWorld=options.membership[handle];
  if(typeof inWorld!=='boolean'||!Array.isArray(ancestry)||ancestry.length>options.maxTextChars)throw Error('Invalid local weapon seed membership');
  models.push({handle,resource,inWorld,groupAncestry:ancestry,worldMatrix:checked(transform.clone().multiply(matrix(mesh.matrixWorld.elements)).multiply(unit)).elements});
 }
 return copyCheckpoint({prefix:options.prefix,cameraHandle:options.cameraHandle,cameraWorldMatrix:options.cameraWorldMatrix,selectedWeapon:options.selectedWeapon,loadedRocket:options.loadedRocket,motion:options.motion,models},options.maxTextChars);
}

export interface OriginalSoloLocalWeaponBindingOptions {
 readonly followOffworldParents:boolean;readonly parentRestoresMembership:boolean;readonly maxTextChars:number;
}
/** Explicit copy parent-setter policy, not a reconstruction of native Director
 * parent setters. Prior parent-local translation and decomposed scale are retained
 * by whichgun; its rotation is the existing copy's fixed weapon Euler basis.
 * Position writes source translation once, retaining the complete local basis.
 * Parent motion follows retained ancestry according to the offworld policy.
 * Rocket reparenting uses zero local translation and its decoded geometry. */
export function createOriginalSoloLocalWeaponBinding(options:OriginalSoloLocalWeaponBindingOptions):ReceiverLocalWeaponWorldOptions['bindModels'] {
 if(!options||typeof options.followOffworldParents!=='boolean'||typeof options.parentRestoresMembership!=='boolean')throw Error('Invalid local weapon binding policy');
 const followOffworldParents=options.followOffworldParents,parentRestoresMembership=options.parentRestoresMembership,maxTextChars=options.maxTextChars;limit(maxTextChars);
 return (operation:ReceiverLocalWeaponBindingOperation,previous:ReceiverLocalWeaponWorldCheckpoint)=>{
  const state=copyCheckpoint(previous,maxTextChars),camera=matrix(state.cameraWorldMatrix),cameraInverse=inverse(camera);
  let models=state.models.map(model=>({...model})),loadedRocket=state.loadedRocket;
  const follows=(model:ReceiverLocalWeaponModelCapture,parent:string)=>model.groupAncestry.some(group=>normalized(group)===normalized(parent))&&(model.inWorld||followOffworldParents);
  const moveChildren=(parent:string,delta:THREE.Matrix4)=>{models=models.map(model=>follows(model,parent)?{...model,worldMatrix:frozenMatrix(delta.clone().multiply(matrix(model.worldMatrix)))}:model);};
  const get=(handle:ReceiverLocalWeaponHandle)=>models.find(model=>model.handle===handle)!;
  const retainedLocal=(model:ReceiverLocalWeaponModelCapture)=>{
   const parent=model.groupAncestry[0];
   if(parent===undefined)return matrix(model.worldMatrix);
   if(normalized(parent)===normalized(state.cameraHandle))return checked(cameraInverse.clone().multiply(matrix(model.worldMatrix)));
   const parentModel=models.find(candidate=>candidate.handle===normalized(parent));
   if(!parentModel)throw Error('Unknown local weapon immediate parent');
   return checked(inverse(matrix(parentModel.worldMatrix)).multiply(matrix(model.worldMatrix)));
  };
  const replace=(model:ReceiverLocalWeaponModelCapture)=>{models=models.map(old=>old.handle===model.handle?model:old);};
  const parentRocket=()=>{const rpg=get('rpg'),rocket=get('rocket');replace({...rocket,worldMatrix:rpg.worldMatrix,groupAncestry:Object.freeze(['rpg',...rpg.groupAncestry]),inWorld:parentRestoresMembership&&rpg.inWorld});};
  if(!operation)throw Error('Invalid local weapon binding operation');
  switch(operation.kind){
   case 'camera':{const delta=checked(matrix(operation.cameraWorldMatrix).multiply(cameraInverse));moveChildren(state.cameraHandle,delta);break;}
   case 'whichgun':{
    if(operation.weapon!==null&&!Object.hasOwn(weaponHandles,operation.weapon))throw Error('Invalid local weapon selection');
    models=models.map(model=>model.handle==='rocket'?model:{...model,inWorld:false});
    if(operation.weapon!==null){
     const model=get(weaponHandles[operation.weapon]),old=matrix(model.worldMatrix),local=retainedLocal(model);
     const position=new THREE.Vector3(),quaternion=new THREE.Quaternion(),scale=new THREE.Vector3();local.decompose(position,quaternion,scale);
     const next=checked(camera.clone().multiply(new THREE.Matrix4().compose(position,rotation,scale)));
     const delta=checked(next.clone().multiply(inverse(old)));moveChildren(model.handle,delta);
     replace({...model,worldMatrix:frozenMatrix(next),groupAncestry:Object.freeze([state.cameraHandle]),inWorld:parentRestoresMembership});
     if(operation.weapon==='rpg')parentRocket();
    }
    break;
   }
   case 'rocket':{
    if(typeof operation.loadedRocket!=='boolean')throw Error('Invalid local rocket state');
    if(operation.loadedRocket)parentRocket();else replace({...get('rocket'),inWorld:false});loadedRocket=operation.loadedRocket;break;
   }
   case 'position':{
    if(!Object.hasOwn(weaponHandles,operation.weapon)||operation.weapon!==state.selectedWeapon||!operation.positionSource||![operation.positionSource.x,operation.positionSource.y,operation.positionSource.z].every(Number.isFinite))throw Error('Invalid local weapon position');
    const model=get(weaponHandles[operation.weapon]),old=matrix(model.worldMatrix),local=checked(cameraInverse.clone().multiply(old));
    if(normalized(model.groupAncestry[0]??'')!==normalized(state.cameraHandle))throw Error('Local weapon position requires camera parent');
    local.setPosition(operation.positionSource.x*ORIGINAL_WEAPON_UNIT_SCALE,operation.positionSource.y*ORIGINAL_WEAPON_UNIT_SCALE,operation.positionSource.z*ORIGINAL_WEAPON_UNIT_SCALE);
    const next=checked(camera.clone().multiply(local)),delta=checked(next.clone().multiply(inverse(old)));
    moveChildren(model.handle,delta);replace({...model,worldMatrix:frozenMatrix(next)});break;
   }
   default:throw Error('Unknown local weapon binding operation');
  }
  // Validate generated ancestry, overflow and combined text before publication.
  const answer=copyCheckpoint({...state,models,loadedRocket},maxTextChars);
  return Object.freeze({models:answer.models,loadedRocket:answer.loadedRocket});
 };
}
